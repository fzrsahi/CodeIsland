    public var body: some View {
        let rawChars = Array(text.uppercased())
        let chars: [Character] = {
            if let max = maxChars, rawChars.count > max {
                let prefixCount = max > 2 ? max - 2 : max
                return Array(rawChars.prefix(prefixCount)) + [".", "."]
            }
            return rawChars
        }()
        let px = pixelSize
        let gap: CGFloat = px

        Canvas { ctx, _ in
            var xOff: CGFloat = 0
            for ch in chars {
                guard let glyph = Self.glyphs[ch] else {
                    xOff += 3 * px
                    continue
                }
                for row in 0..<Self.H {
                    for col in 0..<Self.W {
                        if glyph[row * Self.W + col] == 1 {
                            let rect = CGRect(
                                x: xOff + CGFloat(col) * px,
                                y: CGFloat(row) * px,
                                width: px,
                                height: px
                            )
                            ctx.fill(Path(rect), with: .color(color))
                        }
                    }
                }
                xOff += CGFloat(Self.W) * px + gap
            }
        }
        .frame(width: charWidth(chars.count), height: CGFloat(Self.inkRows) * pixelSize)
        .clipped()
    }

    private func charWidth(_ count: Int) -> CGFloat {
        guard count > 0 else { return 0 }
        let px = pixelSize
        return CGFloat(count) * (CGFloat(Self.W) * px + px) - px
    }
